export interface Submittal {
  id: string;
  // Project/Job reference
  jobId?: string;
  jobName: string;
  jobLocation?: string;
  // Quote references (can be multiple)
  quoteIds: string[];
  // Stakeholders
  customers: SubmittalStakeholder[];
  engineers: SubmittalStakeholder[];
  architects: SubmittalStakeholder[];
  // Dates
  bidDate?: string;
  submittalDate: string;
  createdAt: string;
  updatedAt: string;
  // Status
  status: SubmittalStatus;
  currentRevision: number;
  // Items
  items: SubmittalItem[];
  // Revisions history
  revisions: SubmittalRevision[];
  // Configuration options
  config: SubmittalConfig;
  // Metadata
  createdBy: string;
  updatedBy: string;
  // Tags for filtering/organization
  tags?: string[];
}

