export type ItemChangeStatus = 'approved' | 'approved_as_noted' | 'revise' | 'rejected';

export type OverallChangeStatus = 'approved' | 'approved_as_noted' | 'revise_and_resubmit' | 'rejected';

export interface ItemChange {
  id: string;
  itemId: string;
  fixtureType: string;
  catalogNumber: string;
  manufacturer: string;
  status: ItemChangeStatus;
  notes: string[];
  pageReferences?: number[];
  resolved?: boolean;
  resolvedAt?: string;
}

export interface ChangeAnalysis {
  id: string;
  analyzedAt: string;
  analyzedBy: 'ai' | 'manual';
  totalChangesDetected: number;
  itemChanges: ItemChange[];
  overallStatus: OverallChangeStatus;
  summary?: string;
}

export interface ReturnedPdf {
  id: string;
  revisionNumber: number;
  fileName: string;
  fileUrl: string;
  fileSize: number;
  uploadedAt: string;
  uploadedBy: string;
  returnedBy: SubmittalStakeholder;
  receivedDate: string;
  notes?: string;
  // Change analysis results
  changeAnalysis?: ChangeAnalysis;
}

export interface EmailSendRecord {
  id: string;
  sentAt: string;
  sentBy: string;
  recipients: string[];
  subject: string;
  body?: string;
  attachmentUrl: string;
  attachmentName: string;
  attachmentSize: number;
}

export interface SubmittalRevision {
  id?: string; // UUID from backend
  revisionNumber: number;
  generatedAt: string;
  generatedBy: string;
  generatedPdfUrl?: string;
  generatedPdfName?: string;
  generatedPdfSize?: number;
  // Output options used for this revision
  outputOptions: SubmittalOutputOptions;
  // Email send history for this revision
  emailsSent: EmailSendRecord[];
  // Returned PDFs for this revision
  returnedPdfs: ReturnedPdf[];
}

