// -----------------------------------------------------------------------------
// Highlight Definition Types
// -----------------------------------------------------------------------------

export interface HighlightRegion {
  id: string;
  pageNumber: number;
  // Coordinates as percentages (0-100) for zoom independence
  x: number;
  y: number;
  width: number;
  height: number;
  shape: HighlightShape;
  color: string; // hex color
  strokeWidth?: number;
  annotation?: string; // text content for text boxes
  rotation?: number; // for arrows
  tags?: string[]; // user-defined tags for categorization
}

export interface HighlightDefinition {
  id: string;
  specSheetId: string;
  catalogNumber: string;
  manufacturer: string;
  regions: HighlightRegion[];
  createdAt: string;
  createdBy: string;
  updatedAt: string;
  updatedBy: string;
}

// -----------------------------------------------------------------------------
// Spec Sheet Types
// -----------------------------------------------------------------------------

export interface SpecSheetFolder {
  id: string;
  name: string;
  parentId: string | null; // null for root folders
  manufacturer?: string; // If folder is under a manufacturer
  isAutoGenerated: boolean; // true for system-created folders
  createdAt: string;
  createdBy: string;
  specSheetCount?: number; // Number of spec sheets in this folder (from API)
  folderPath?: string; // Full folder path (e.g., "F1/F2")
}

export interface SpecSheet {
  id: string;
  factoryId?: string; // Factory ID from API (used to resolve manufacturer name)
  manufacturer: string;
  fileName: string;
  displayName: string; // User-friendly name (can override fileName)
  categories: SpecSheetCategory[];
  tags: string[]; // User-defined tags for filtering
  folderId?: string; // Optional folder assignment
  folderPath?: string; // Folder path from API (e.g., "F1/F2")
  uploadSource: UploadSource;
  sourceUrl?: string; // Original URL if uploaded from URL
  fileUrl: string; // Stored file location
  fileSize: number; // bytes
  pageCount: number;
  uploadedAt: string;
  uploadedBy: string;
  updatedAt?: string;
  needsReview: boolean; // Flag for stale sheets
  usageCount: number; // How many times used in submittals
  // Computed/joined data
  highlightCount?: number; // Number of highlight definitions for this sheet
}

// -----------------------------------------------------------------------------
// Submittal Item Types
// -----------------------------------------------------------------------------

export interface SubmittalItem {
  id: string;
  submittalId: string;
  // Reference to quote line item (if created from quote)
  quoteLineItemId?: string;
  quoteId?: string;
  // Item details
  fixtureType: string; // e.g., "F1", "F2", "A", "B"
  manufacturer: string;
  catalogNumber: string;
  description: string;
  quantity?: number; // Optional, user can toggle visibility
  // Spec sheet attachment
  specSheetId?: string;
  specSheetPageRange?: { start: number; end: number }; // If only using certain pages
  highlightDefinitionId?: string;
  // Nested objects from API
  specSheet?: SpecSheet; // Populated from GraphQL response
  highlightVersion?: HighlightDefinition; // Populated from GraphQL response
  // Status
  matchStatus: SpecSheetMatchStatus;
  itemApprovalStatus?: ItemApprovalStatus;
  approvalNotes?: string;
  // Ordering
  sortOrder: number;
}

